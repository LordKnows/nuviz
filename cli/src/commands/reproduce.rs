use anyhow::Result;
use serde_json::Value;
use std::path::Path;

use crate::cli::ReproduceArgs;
use crate::commands::common::find_experiment;
use crate::data::meta::read_meta_value;

pub fn run(args: ReproduceArgs, base_dir: &Path) -> Result<()> {
    let exp = find_experiment(base_dir, &args.experiment, args.project.as_deref())?;
    let Some(doc) = read_meta_value(&exp.dir) else {
        anyhow::bail!("no readable meta.json found for '{}'", exp.qualified_name());
    };
    print!("{}", render(&exp.qualified_name(), &doc));
    Ok(())
}

/// Quote an argument for a POSIX shell when it needs it.
fn shell_quote(arg: &str) -> String {
    let safe = !arg.is_empty()
        && arg
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "_-./=:@%+,".contains(c));
    if safe {
        arg.to_string()
    } else {
        format!("'{}'", arg.replace('\'', "'\\''"))
    }
}

/// Build a commented shell script that recreates the experiment's setup.
fn render(name: &str, doc: &Value) -> String {
    let text = |key: &str| doc.get(key).and_then(Value::as_str);
    let mut out = String::new();
    let mut line = |s: &str| {
        out.push_str(s);
        out.push('\n');
    };

    line(&format!("# Reproduction guide for '{name}'"));
    line("# Generated by nuviz reproduce");
    if let Some(t) = text("start_time") {
        line(&format!("# Originally started: {t}"));
    }
    if let Some(status) = text("status") {
        line(&format!("# Final status: {status}"));
    }
    line("");

    if let Some(hash) = text("git_hash") {
        line("# --- Code ---");
        line(&format!("git checkout {hash}"));
        if doc.get("git_dirty").and_then(Value::as_bool) == Some(true) {
            line("# WARNING: tracked files had uncommitted changes when this ran,");
            line("#          so this commit alone may not reproduce the result.");
        }
        line("");
    }

    if let Some(py) = text("python_version") {
        line("# --- Environment ---");
        line(&format!(
            "# Python {}",
            py.split_whitespace().next().unwrap_or(py)
        ));
    }
    let packages: Vec<&str> = doc
        .get("pip_packages")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    if !packages.is_empty() {
        line("pip install \\");
        for (i, pkg) in packages.iter().enumerate() {
            let cont = if i + 1 < packages.len() { " \\" } else { "" };
            line(&format!("  {}{cont}", shell_quote(pkg)));
        }
    }
    if text("python_version").is_some() || !packages.is_empty() {
        line("");
    }

    let hardware: Vec<String> = [
        ("GPU", "gpu_model"),
        ("CUDA", "cuda_version"),
        ("Host", "hostname"),
    ]
    .iter()
    .filter_map(|(label, key)| Some(format!("# {label}: {}", text(key)?)))
    .collect();
    if !hardware.is_empty() {
        line("# --- Hardware ---");
        for h in &hardware {
            line(h);
        }
        line("");
    }

    if let Some(config) = doc.get("config").filter(|c| !c.is_null()) {
        line("# --- Hyperparameters ---");
        let pretty = serde_json::to_string_pretty(config).unwrap_or_default();
        for l in pretty.lines() {
            line(&format!("# {l}"));
        }
        line("");
    }
    if let Some(seed) = doc.get("seed").and_then(Value::as_i64) {
        line(&format!("# Seed: {seed}"));
        line("");
    }

    let argv: Vec<&str> = doc
        .get("argv")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    // argv[0] is "" or "-c" for interactive / inline runs: nothing to re-run.
    if argv
        .first()
        .is_some_and(|a| !a.is_empty() && *a != "-c" && *a != "-")
    {
        line("# --- Command ---");
        if let Some(cwd) = text("cwd") {
            line(&format!("cd {}", shell_quote(cwd)));
        }
        let quoted: Vec<String> = argv.iter().map(|a| shell_quote(a)).collect();
        line(&format!("python {}", quoted.join(" ")));
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_full_guide() {
        let doc = serde_json::json!({
            "git_hash": "abc123", "git_dirty": true,
            "python_version": "3.11.4 (main, ...)",
            "pip_packages": ["numpy==1.26.0", "torch==2.2.0"],
            "gpu_model": "RTX 4090", "hostname": "node7",
            "config": {"lr": 0.001}, "seed": 7,
            "argv": ["train.py", "--name", "my run", "--lr=1e-3"],
            "cwd": "/home/me/proj", "status": "done"
        });
        let out = render("proj/exp", &doc);
        assert!(out.contains("git checkout abc123"));
        assert!(out.contains("uncommitted changes"));
        assert!(out.contains("# Python 3.11.4\n"));
        assert!(out.contains("  numpy==1.26.0 \\\n  torch==2.2.0\n"));
        assert!(out.contains("# GPU: RTX 4090"));
        assert!(out.contains("#   \"lr\": 0.001"));
        assert!(out.contains("# Seed: 7"));
        assert!(out.contains("cd /home/me/proj\npython train.py --name 'my run' --lr=1e-3\n"));
    }

    #[test]
    fn test_minimal_meta_and_inline_script() {
        let out = render("exp", &serde_json::json!({"argv": ["-c"], "seed": -1}));
        assert!(out.starts_with("# Reproduction guide for 'exp'"));
        assert!(!out.contains("--- Command ---"));
        assert!(out.contains("# Seed: -1"));
    }

    #[test]
    fn test_shell_quote() {
        assert_eq!(shell_quote("plain-arg_1.0"), "plain-arg_1.0");
        assert_eq!(shell_quote("it's"), "'it'\\''s'");
        assert_eq!(shell_quote(""), "''");
    }
}
